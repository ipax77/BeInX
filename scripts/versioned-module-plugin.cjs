const fs = require('fs');

// Keep the checked-in C# import path in sync with the bundle emitted by webpack.
module.exports = class VersionedModulePlugin {
    constructor(sourcePath, namespace, modulePath) {
        this.sourcePath = sourcePath;
        this.namespace = namespace;
        this.modulePath = modulePath;
    }

    apply(compiler) {
        compiler.hooks.afterEmit.tap('VersionedModulePlugin', compilation => {
            if (compilation.getErrors().length) return;
            const source = `// <auto-generated />\n// Generated by npm run build from package.json.\nnamespace ${this.namespace};\n\ninternal static class JsModule\n{\n    internal const string Path = "${this.modulePath}";\n}\n`;
            if (!fs.existsSync(this.sourcePath) || fs.readFileSync(this.sourcePath, 'utf8') !== source) {
                fs.writeFileSync(this.sourcePath, source);
            }
        });
    }
};
